// Arithmetic operators
// In JavaScript, arithmetic operators are used to perform
// mathematical operations on operands.

// +   Adds two operands -> num1 + num2
// -   Subtracts the right operand from the left operand -> num1 - num2
// *   Multiplies two operands -> num1 * num2
// /   Divides the left operand by the right operand -> num1 / num2
// %   Modulus operator. Returns the division remainder -> num1 % num2
// ++  Increment operator. Increases the operand value by one -> num1++ or ++num1
// --  Decrement operator. Decreases the operand value by one -> num2-- or --num2

let a = 5, b = 10;
console.log(a + b); // 15
console.log(a - b); // -5
console.log(a * b); // 50
console.log(a / b); // 0.5
console.log(a % b); // 5
console.log(a++);   // 5 (post-increment)
console.log(a);     // 6
console.log(++a);   // 7 (pre-increment)
console.log(a);     // 7
console.log(b--);   // 10 (post-decrement)
console.log(b);     // 9
console.log(--b);   // 8 (pre-decrement)
console.log(b);     // 8