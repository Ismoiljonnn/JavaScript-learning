// Accessing Object Properties – You can access the
// value of an object's property using its key.

// Using Dot Notation (.)
const programmer = {
  name: 'Ismoiljon',
  age: 16
};

console.log(programmer.name); // "Ismoiljon"

// Using Bracket Notation ([])
const programmer2 = {
  name: 'Ismoiljon',
  age: 16
};

console.log(programmer2['name']); // "Ismoiljon"