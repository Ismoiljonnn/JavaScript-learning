// Declaring an Object – Objects are created using curly braces {},
// where each property follows a key: value structure.

const programmer = {
  name: 'Ismoiljon',
  age: 16
};

console.log(typeof programmer); // "object"

let person = {
  name: 'Ismoiljon', // Key: name  | Value: 'Ismoiljon'
  age: 16            // Key: age   | Value: 16
};