// To add elements to an array, you can use the
// push() or unshift() array methods.

// push() method adds an element to the end of an array:
let languages = ['js', 'java'];

languages.push('go');

console.log(languages); // ['js', 'java', 'go']

// unshift() method adds an element to the beginning of an array:

let languages2 = ['js', 'java'];

languages2.unshift('go');

console.log(languages); // ['go', 'js', 'java']