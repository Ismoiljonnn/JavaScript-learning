// Array literal notation
// The easiest way to create an array is using an array literal,
// which is created using square brackets ([]).

const languages = ['js', 'java', 'go'];

// Using the new keyword
// In JavaScript, arrays can also be created using the new keyword.

const languages2 = new Array('js', 'java', 'go');

// Arrays can store elements of different data types together
// within the same array.

// Empty array
const emptyArray = [];

// Array of numbers
const sonArray = [1, 2, 9, -2];

// Array of strings
const stringArray = ['Javascript', 'Java', 'Go'];

// Array with mixed data types
const mixedArray = ['Javascript', 2, false, null];