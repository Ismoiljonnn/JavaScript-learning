// Function – one of the core fundamentals of JavaScript that
// allows executing a specific task. A function runs when it is
// invoked (called) from another part of the code. It enables
// code reusability, meaning you can declare it once and use it
// in multiple places.

// General syntax

// function functionName(parameter1, parameter2, ...,   parameterN) {
//   statement 1;
//   statement 2;
//   statement 3;
//   return output;
// }

// functionName(argument1, argument2, ..., argumentN);

// Function example

function myFunction(num1, num2) {
  return num1 + num2;
}

myFunction(10, 20); // 30 // Function call
myFunction(20, 30); // 50 // Function call

// Declaring types:
// Function declaration
// Function expression
// Arrow function